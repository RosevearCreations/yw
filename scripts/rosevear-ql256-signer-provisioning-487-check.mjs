import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,statSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createPrivateKey,createPublicKey,sign,verify} from 'node:crypto';
import {sourceEvidenceA,ql256Inventory,provisionOperatorSigner,ql256RequiredNames} from '../server/rosevear-ql256-signer-provisioning-487.mjs';
assert.equal(sourceEvidenceA.sourceShaA,sourceEvidenceA.sourceCiHeadSha);
assert.equal(sourceEvidenceA.sourceCiConclusion,'success');
const status=ql256Inventory({vercelEnvNames:[],signerPrivateStatus:'UNKNOWN'});
assert.equal(status.signerProvisioningDecision,'SIGNER_STATUS_UNKNOWN');
assert.equal(status.vercelEnvCount,0);assert.equal(status.decision,'HOLD');
assert.equal(status.ownerTestDecision,'NOT_GIVEN');
assert.ok(ql256RequiredNames.some(v=>v.name==='YWI_QL256_SIGNER_PASSPHRASE'));
const privateRoot=mkdtempSync(join(tmpdir(),'ql256-private-'));
const privateDir=join(privateRoot,'operator');
try {
 mkdirSync(privateDir,{mode:0o700});
 const input={outputDirectory:privateDir,repositoryRoot:process.cwd(),passphrase:'a sufficiently long private operator test passphrase'};
 const result=provisionOperatorSigner(input);
 assert.equal(result.publicSpkiSha256.length,64);
 assert.equal(result.independentlyCustodied,false);assert.equal(result.originalSignedProofCreated,false);
 const keyFile=join(privateDir,'ql256-ed25519-encrypted-pkcs8.pem');
 assert.equal(statSync(keyFile).mode&0o077,0);
 const key=readFileSync(keyFile,'utf8');
 assert.ok(key.includes('ENCRYPTED PRIVATE KEY'));assert.ok(!key.includes('BEGIN PRIVATE KEY-----'));
 const recovered=createPrivateKey({key,passphrase:input.passphrase});
 const publicKey=createPublicKey(readFileSync(join(privateDir,'ql256-ed25519-public-spki.pem')));
 const challenge=Buffer.from('QL256 unique test challenge');
 assert.ok(verify(null,challenge,publicKey,sign(null,challenge,recovered)));
 assert.throws(()=>provisionOperatorSigner(input),/NO_OVERWRITE/);
 assert.throws(()=>provisionOperatorSigner({...input,passphrase:'short'}),/PASSPHRASE_REQUIRED/);
}finally{rmSync(privateRoot,{recursive:true,force:true});}
assert.equal(existsSync('docs/integration/ql246-source-proof.json'),false);
const handoff=readFileSync('docs/integration/ql256-build487-PENDING.txt','utf8');
for(const marker of ['QL-256','SIGNER_STATUS_UNKNOWN','source SHA A','proof commit B','NOT_GIVEN','DISCONNECTED / HOLD'])assert.ok(handoff.includes(marker),marker);
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.ok(pkg.scripts['test:rosevear-ql256-signer-provisioning-487']);
assert.ok(readFileSync('.github/workflows/staging-browser-integration.yml','utf8').includes('npm run test:rosevear-ql256-signer-provisioning-487'));
console.log('QL256 Build 487 real Ed25519 encrypted operator provisioning checks PASS');
