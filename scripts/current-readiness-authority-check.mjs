#!/usr/bin/env node
import fs from 'node:fs';
const read=(file)=>fs.readFileSync(file,'utf8');
const checks=[]; const add=(name,ok)=>checks.push({name,ok:!!ok});
const migration=read('sql/195_current_readiness_authority.sql');
const endpoint=read('supabase/functions/admin-it-control/index.ts');
const ui=read('js/it-readiness-ui.js');
const help=read('help.html');
const docs=[read('README.md'),read('docs/ACTIVE_PROJECT_HANDBOOK.md'),read('docs/NEXT_STEPS_AND_SANITY_CHECK.md')];
add('schema195-migration-present',fs.existsSync('sql/195_current_readiness_authority.sql'));
add('legacy-table-preserved',migration.includes('from public.admin_production_readiness_checks p'));
add('historical-archive-audit-only',migration.includes("'production_readiness'::text as archive_source")&&migration.includes('true::boolean as audit_only'));
add('live-readiness-replaced',migration.includes('create or replace view public.v_production_readiness_checklist'));
add('live-readiness-schema-derived',migration.includes('from public.v_schema_drift_status s'));
add('live-readiness-release-derived',migration.includes('from public.v_it_release_authority_status r'));
add('live-readiness-scorecard-derived',migration.includes('from public.v_it_scorecard_progress_truth_status t'));
add('live-readiness-current-todo-derived',migration.includes('from public.v_it_current_admin_todo_status t'));
add('live-readiness-help-seo-derived',migration.includes('ywi_public_web_authority_release_assertions'));
add('live-readiness-finance-provider-safe',migration.includes('finance_job_completion_posting_execution_controls')&&migration.includes('provider_mutation_enabled=true'));
add('legacy-foundation-rows-not-current',migration.includes("check_key in ('saved_filters','close_wizard_steps','server_pagination_foundation','bank_csv_import_foundation','mobile_action_cards')"));
add('schema195-assertions-present',migration.includes('ywi_current_readiness_authority_assertions'));
add('schema195-business-rails-unchanged',migration.includes('open_business_acceptance_unchanged')&&migration.includes(')=11'));
add('schema195-no-business-auto-close',migration.includes("'business_rail_auto_close',false"));
add('schema195-no-history-delete',migration.includes("'historical_audit_delete',false"));
add('schema195-drift-marker',migration.includes('select 195::int as expected_schema_version')&&migration.includes("values(195,'195_current_readiness_authority'"));
add('endpoint-consumes-live-view',endpoint.includes('["v_production_readiness_checklist", "sort_order", true, 160]'));
add('ui-production-readiness-panel-retained',ui.includes("panel('production_readiness','Release','Production readiness')"));
add('help-current-readiness-language',/historical[^.]{0,120}audit/i.test(help)&&/Production readiness/i.test(help));
add('active-docs-no-build-ledgers',docs.every((text)=>!(/\bBuild\s+\d+\b/i.test(text))&&!(/\b[0-9a-f]{40}\b/i.test(text))));
const passed=checks.filter((item)=>item.ok).length;
console.log(`Current readiness authority gate: ${passed}/${checks.length} passed`);
for(const item of checks) console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`);
process.exit(passed===checks.length?0:1);
