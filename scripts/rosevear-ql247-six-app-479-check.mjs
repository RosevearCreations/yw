import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {applications,evidenceFields,pendingSnapshot,reconcile} from '../server/rosevear-ql247-six-app-479.mjs';
assert.equal(applications.length,6);
assert.equal(new Set(applications.map(x=>x[1])).size,6);
assert.equal(evidenceFields.length,13);
const snapshot=pendingSnapshot(),r=reconcile(snapshot);
assert.equal(r.connection_state,'DISCONNECTED');
assert.equal(r.pilot_authorized,false);
assert.equal(r.write_commands_enabled,false);
assert.equal(r.dispatch_enabled,false);
assert.ok(r.applications.every(x=>x.readiness==='HOLD'&&x.missing.length===13));
assert.throws(()=>reconcile(snapshot.slice(1)),/QL247_HOLD_APP_SET/);
assert.throws(()=>reconcile([...snapshot.slice(0,5),snapshot[0]]),/QL247_HOLD_IDENTITY/);
assert.throws(()=>reconcile(snapshot.map((x,i)=>i===0?{...x,evidence:{...x.evidence,extra:'VERIFIED'}}:x)),/QL247_HOLD_SCHEMA/);
assert.throws(()=>reconcile(snapshot.map((x,i)=>i===0?{...x,evidence:{...x.evidence,ci_url:true}}:x)),/QL247_HOLD_EVIDENCE_VALUE/);
const fullyMarked=snapshot.map(x=>({...x,evidence:Object.fromEntries(evidenceFields.map(k=>[k,'VERIFIED']))}));
const positive=reconcile(fullyMarked);
assert.ok(positive.applications.every(x=>x.readiness==='INDEPENDENT_REVIEW_REQUIRED'));
assert.equal(positive.connection_state,'DISCONNECTED');
assert.equal(positive.pilot_authorized,false);
assert.equal(existsSync('docs/integration/ql246-source-proof.json'),false);
const handoff=readFileSync('docs/integration/ql247-build479-PENDING.txt','utf8');
for(const [,repo] of applications)assert.ok(handoff.includes(repo));
for(const token of ['DISCONNECTED','HOLD','NOT PROVISIONED','UNVERIFIED','NOT GIVEN','GET /api/integration/v1/health','GET /api/integration/v1/capabilities'])
 assert.ok(handoff.includes(token),token);
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.ok(pkg.scripts['test:rosevear-ql247-six-app-479']);
assert.ok(readFileSync('.github/workflows/staging-browser-integration.yml','utf8').includes('npm run test:rosevear-ql247-six-app-479'));
console.log('QL247 Build 479 six-app fail-closed readiness PASS');
