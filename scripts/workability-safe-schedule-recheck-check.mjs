import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const read = path => fs.readFileSync(path, 'utf8');
const code = read('js/workability-safe-schedule-recheck.js');
const ui = read('js/admin-weather-workability-ui.js');
const index = read('index.html');
const workflow = read('.github/workflows/staging-browser-integration.yml');
const pkg = JSON.parse(read('package.json'));
const sandbox = {window:{},document:{}};
vm.runInNewContext(code,sandbox);
const {assess} = sandbox.window.YWIWorkabilitySafeScheduleRecheck;
assert.equal(typeof assess,'function');
const now=Date.parse('2026-10-13T22:00:00Z');
const dispatch={id:'d1',scheduled_start:'2026-10-13T23:00:00Z',scheduled_end:'2026-10-14T01:00:00Z',schedule_status:'scheduled',workability_state:'review'};
const observation={id:'o1',dispatch_schedule_item_id:'d1',latest_decision_id:'v1',observed_at:'2026-10-13T21:00:00Z',service_date:'2026-10-13',weather_condition:'Ground dry',restriction_guidance_count:0,linked_hse_packet_id:'h1'};
const decision={id:'v1',observation_id:'o1',decision_state:'workable',decided_by_profile_id:'supervisor1',decision_at:'2026-10-13T21:10:00Z'};
const packet={id:'h1',packet_number:'HSE-1',packet_status:'open',weather_monitoring_required:true,weather_monitoring_completed:true};
const payload={workability_queue:[observation],workability_decisions:[decision],workability_hse_packets:[packet]};
const good={verified:true,level:'approve'};
const evaluate=(patch={},permission=good,other=payload)=>assess({...dispatch,...patch},other,permission,now);
assert.equal(evaluate().status,'OPERATOR_RECHECK','current evidence allows only operator recheck, not dispatch approval');
assert.equal(evaluate({}, {verified:false,level:'view'}).status,'HOLD','Safety permission is mandatory');
assert.equal(evaluate({schedule_status:'on_hold'}).status,'HOLD','an existing hold cannot be cleared');
assert.equal(evaluate({workability_state:'blocked'}).status,'HOLD','an existing Safety workability restriction cannot be cleared');
assert.equal(evaluate({},good,{...payload,workability_queue:[]}).status,'HOLD','unlinked observations do not authorize review');
assert.equal(evaluate({},good,{...payload,workability_queue:[{...observation,observed_at:'2026-10-11T20:00:00Z'}]}).status,'HOLD','stale weather fails closed');
assert.equal(evaluate({},good,{...payload,workability_decisions:[{...decision,decision_state:'postpone'}]}).status,'HOLD','supervisor postpone remains binding');
assert.equal(evaluate({},good,{...payload,workability_decisions:[]}).status,'HOLD','missing latest decision fails closed');
assert.equal(evaluate({},good,{...payload,workability_hse_packets:[{...packet,weather_monitoring_completed:false}]}).status,'HOLD','incomplete HSE monitoring blocks');
assert.equal(evaluate({},good,{...payload,workability_queue:[{...observation,restriction_guidance_count:1}]}).status,'REVIEW','guidance restriction does not self-clear');
assert.ok(ui.includes('YWIWorkabilitySafeScheduleRecheck?.mount?.(el,{api})'));
assert.ok(index.includes('/js/workability-safe-schedule-recheck.js?'));
assert.ok(!code.includes('manageOperations(') && !code.includes('manageJobsEntity(') && !code.includes('.update('),'Build 395 must remain read-only');
assert.ok(pkg.scripts['test:workability-safe-schedule-recheck'] && pkg.scripts['test:browser:workability-safe-schedule-recheck']);
assert.ok(workflow.includes('npm run test:workability-safe-schedule-recheck'));
assert.ok(workflow.includes('npm run test:browser:workability-safe-schedule-recheck'));
console.log('Build 395 workability hold, permission, HSE, freshness, and read-only checks PASS');
